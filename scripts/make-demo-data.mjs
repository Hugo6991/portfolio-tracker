#!/usr/bin/env node
// Writes synthetic data/portfolio.json and data/expenses.json for the open source copy.
// Every number is invented. Labels are generic on purpose: no real exchange account,
// wallet label, bank or holding appears here.
//
//   node scripts/make-demo-data.mjs            -> writes into ./data (refuses if the files look real)
//   node scripts/make-demo-data.mjs --out DIR  -> writes DIR/data/portfolio.json and DIR/data/expenses.json
import { mkdirSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

const outArg = process.argv.indexOf("--out");
const root = outArg > -1 ? process.argv[outArg + 1] : process.cwd();
const dir = join(root, "data");
mkdirSync(dir, { recursive: true });

const stamp = new Date().toISOString();
const day = stamp.slice(0, 10);
const addr = (n) => `0x${"0".repeat(36)}${n.toString(16).padStart(4, "0")}`;

const cex = [
  { id: "exchange-a", name: "Exchange A", type: "cex", assets: ["USDT", "BTC", "BNB", "TSLA", "SPCX"], valueUsd: 17_110, lastUpdate: day },
  { id: "exchange-b", name: "Exchange B", type: "cex", assets: ["ETH", "USDC", "SOL", "UNI"], valueUsd: 13_600, lastUpdate: day },
  { id: "exchange-c", name: "Exchange C", type: "cex", assets: ["USDT", "SUI", "TSLA"], valueUsd: 4_360, lastUpdate: day },
  { id: "exchange-d", name: "Exchange D", type: "cex", assets: ["BTC", "AVAX"], valueUsd: 2_280, lastUpdate: day },
  { id: "exchange-e", name: "Exchange E", type: "cex", assets: ["USDT", "LINK"], valueUsd: 1_500, lastUpdate: day }
];
const wallets = [
  { id: "wallet-main", name: "Main wallet", type: "wallet", chain: "evm", address: addr(1), assets: ["ETH", "USDC", "UNI", "Aave V3"], valueUsd: 13_900, lastUpdate: day },
  { id: "wallet-cold", name: "Cold wallet", type: "wallet", chain: "evm", address: addr(2), assets: ["BTC", "ETH", "AAVE"], valueUsd: 11_220, lastUpdate: day },
  { id: "wallet-defi", name: "DeFi wallet", type: "wallet", chain: "evm", address: addr(3), assets: ["Morpho", "Uniswap V3", "LINK"], valueUsd: 10_800, lastUpdate: day },
  { id: "wallet-arbitrum", name: "Arbitrum wallet", type: "wallet", chain: "evm", address: addr(4), assets: ["ARB", "USDT", "ETH"], valueUsd: 3_900, lastUpdate: day },
  { id: "wallet-hot", name: "Hot wallet", type: "wallet", chain: "evm", address: addr(5), assets: ["BNB", "USDT", "HYPE", "Hyperliquid"], valueUsd: 5_700, lastUpdate: day }
];
const fx = 32;
const banks = [
  { id: "bank-cash-twd", name: "Bank A", type: "bank", assets: ["TWD"], nativeAmount: 160_000, nativeCurrency: "TWD", valueTwd: 160_000, valueUsd: 5_000, lastUpdate: day },
  { id: "bank-cash-usd", name: "Bank B", type: "bank", assets: ["USD"], nativeAmount: 3_000, nativeCurrency: "USD", valueTwd: 96_000, valueUsd: 3_000, lastUpdate: day }
];
const sum = (rows) => rows.reduce((s, r) => s + (r.valueUsd || 0), 0);
const portfolio = {
  meta: { fxTwdUsd: fx, baseCurrency: "USD", exportedAt: stamp, note: "Synthetic demo data generated by scripts/make-demo-data.mjs. Nothing here is a real balance." },
  summary: { totalUsd: sum(cex) + sum(wallets) + sum(banks), cexUsd: sum(cex), walletUsd: sum(wallets), bankUsd: sum(banks), lastUpdate: day },
  cex,
  wallets,
  banks
};

// Expenses: three years of monthly totals in TWD with a gentle seasonal shape.
const categories = ["food", "traffic", "work", "entertainment", "shopping", "health", "other"];
const monthly = {};
const yearTotals = {};
for (const year of ["2024", "2025", "2026"]) {
  monthly[year] = [];
  for (let m = 1; m <= 12; m++) {
    const i = (Number(year) - 2024) * 12 + m;
    const base = 42_000 + 6_000 * Math.sin(i / 2.3) + 1_500 * Math.cos(i / 5);
    const row = { month: `${year}-${String(m).padStart(2, "0")}`, total: 0 };
    const weights = [0.34, 0.08, 0.05, 0.1, 0.15, 0.06, 0.22];
    categories.forEach((c, k) => { row[c] = Math.round(base * weights[k] * (1 + 0.15 * Math.sin(i * (k + 1)))); });
    row.total = categories.reduce((s, c) => s + row[c], 0);
    monthly[year].push(row);
  }
  yearTotals[year] = monthly[year].reduce((s, r) => s + r.total, 0);
}
const expenses = {
  meta: {
    currency: "TWD",
    note: "Synthetic demo expenses generated by scripts/make-demo-data.mjs. Months after actualThrough are forecast.",
    actualThrough: "2026-09-30",
    partialActuals: {},
    yearTotals
  },
  monthly
};

for (const [name, body] of [["portfolio.json", portfolio], ["expenses.json", expenses]]) {
  const target = join(dir, name);
  if (outArg === -1 && existsSync(target) && !readFileSync(target, "utf8").includes("make-demo-data.mjs")) {
    console.error(`Refusing to overwrite ${target}: it does not look like demo data. Use --out DIR.`);
    process.exit(1);
  }
  writeFileSync(target, JSON.stringify(body, null, 2) + "\n");
  console.log("wrote", target);
}
